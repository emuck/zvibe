/* ---- the single-record save of a version 3 firmware (unchanged) ---- */
/* SmartEEPROM save header structure */
typedef struct {
    uint32_t magic;
    uint32_t data_size;
    uint32_t checksum;
} save_header_t;

/* A save's checksum is a CRC-32 (save_crc32). The earlier shift-and-xor sum kept only the
 * last 32 bytes, so a change anywhere before them went unnoticed; a save written by an older
 * firmware therefore fails this check and is ignored. */
static uint32_t calculate_checksum(const void *data, size_t size) {
    return save_crc32(data, size);
}

/* Save callback - save to both RAM and SmartEEPROM */
static int save_callback(const void *data, size_t size) {
    size_t total_size = sizeof(save_header_t) + size + SAVE_END_MARK_BYTES + 3;
    
    if (total_size > SAVE_CAP) {
        printf("\n[ERROR: save data requires %zu bytes, SmartEEPROM size is %d]\n", total_size, (int)SAVE_CAP);
        return 0;
    }
    
    // Save directly to SmartEEPROM with header (no RAM buffer needed)
    save_header_t header = {
        .magic = SAVE_MAGIC_HEADER,
        .data_size = size,
        .checksum = calculate_checksum(data, size)
    };
    
    /* Header and data go into the page buffer together and are committed with one flush. Committing
     * the header first and the data after it was not reliable once a larger save had been stored
     * before: the data written after the first flush could be lost at the next reset, and the
     * header was left describing data that was not there (the CRC now rejects such a save). */
    if (!smarteeprom_write_raw(SAVE_BASE, &header, sizeof(header)) ||
        !smarteeprom_write_raw(SAVE_BASE + sizeof(header), data, size) ||
        !smarteeprom_write_end_mark(SAVE_BASE + (uint32_t)(sizeof(header) + size))) {
        printf("\n[ERROR: failed to write the save to flash]\n");
        return 0;
    }
    if (!smarteeprom_flush()) {
        printf("\n[ERROR: the SmartEEPROM did not finish the save]\n");
        return 0;
    }
    
    return 1;
}

/* Restore callback - restore from SmartEEPROM only */
static size_t restore_callback(void *buffer, size_t max_size) {
    save_header_t header;
    
    // Read from SmartEEPROM 
    if (smarteeprom_read_data(SAVE_BASE, &header, sizeof(header))) {
        if (header.magic == SAVE_MAGIC_HEADER && header.data_size > 0 && header.data_size <= max_size ) {
            if (smarteeprom_read_data(SAVE_BASE + sizeof(header), buffer, header.data_size)) {
                uint32_t calculated_checksum = calculate_checksum(buffer, header.data_size);
                if (calculated_checksum == header.checksum) {
                    return header.data_size;
                }
            }
        }
    }
    
    return 0;
}

/* Check for existing save at startup */
static void check_existing_save(void) {
    save_header_t header;
    if (smarteeprom_read_data(SAVE_BASE, &header, sizeof(header))) {
        if (header.magic == SAVE_MAGIC_HEADER && header.data_size > 0) {
            printf("\n[Existing save detected - type 'restore' to load]\n");
        }
    }
}

