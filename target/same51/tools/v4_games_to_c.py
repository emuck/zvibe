"""
v4_games_to_c.py - embed several version 4 stories in one SAM E51 firmware.

Writes a C file with one const array per story and the table the multi-game V4 firmware's
menu reads (v4_games[], v4_num_games). Each story is checked: it must be a version 4 story file
with a consistent header. The firmware needs a story buffer big enough for the largest story's
dynamic memory plus 1 KB (the core's reserve); this script prints it for the Makefile.

    v4_games_to_c.py [--limit BYTES] [--name-from-header] OUTPUT.c [Name=]story.z4 ...
    v4_games_to_c.py --buffer story.z4 ...        # print the story buffer size to build with
    v4_games_to_c.py --list story.z4 ...          # sizes and the flash used, no output file

Names default to the file name's first word, capitalised ("bureaucracy-r116-s870602.z4" gives
"Bureaucracy r116"). Give "Name=file" to choose. At most 9 stories (the menu takes one digit).
"""
import os
import re
import struct
import sys

MAX_GAMES = 9
CORE_RESERVE = 1024          # Z_LEGACY_STACK_RESERVE_BYTES in src/core/zvibe_core.c
SMARTEEPROM = 16384


def die(msg):
    print("error:", msg, file=sys.stderr)
    sys.exit(1)


def read_story(path):
    with open(path, "rb") as f:
        d = f.read()
    if len(d) < 64:
        die(f"{path}: too short to be a story file")
    if d[0] != 4:
        die(f"{path}: version {d[0]}, not a version 4 story")
    dyn = struct.unpack(">H", d[14:16])[0]
    if dyn < 64 or dyn >= len(d):
        die(f"{path}: static memory base {dyn} is not inside the file")
    return d, dyn


def default_name(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    m = re.match(r"([A-Za-z0-9]+)(?:-r(\d+))?", stem)
    if not m:
        return stem[:24]
    word = m.group(1)
    names = {"amfv": "A Mind Forever Voyaging", "nordandbert": "Nord and Bert", "generic": "Generic",
             "trinity": "Trinity", "bureaucracy": "Bureaucracy"}
    name = names.get(word.lower(), word.capitalize())
    return name


def parse(args):
    games = []
    for a in args:
        if "=" in a and not os.path.exists(a):
            name, path = a.split("=", 1)
        else:
            name, path = None, a
        data, dyn = read_story(path)
        games.append({"name": name or default_name(path), "path": path, "data": data, "dyn": dyn})
    return games


def buffer_size(games):
    need = max(g["dyn"] for g in games) + CORE_RESERVE
    return (need + 255) // 256 * 256


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv):
    limit = None
    args = []
    mode = "write"
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--limit":
            limit = int(argv[i + 1], 0); i += 2; continue
        if a == "--buffer":
            mode = "buffer"
        elif a == "--list":
            mode = "list"
        else:
            args.append(a)
        i += 1
    if mode == "write":
        if len(args) < 2:
            die(__doc__)
        out, args = args[0], args[1:]
    if not args:
        die("no stories given")
    if len(args) > MAX_GAMES:
        die(f"{len(args)} stories: the menu takes at most {MAX_GAMES}")
    games = parse(args)
    total = sum(len(g["data"]) for g in games)
    if limit is not None and total > limit:
        for g in games:
            print(f"  {len(g['data']):8d}  {g['name']}", file=sys.stderr)
        die(f"the stories total {total} bytes, over the limit of {limit}")
    if mode == "buffer":
        print(buffer_size(games))
        return
    if mode == "list":
        for g in games:
            print(f"{len(g['data']):8d}  dynamic {g['dyn']:6d}  {g['name']}  ({g['path']})")
        print(f"{total:8d}  total, story buffer {buffer_size(games)}")
        return

    with open(out, "w") as f:
        f.write("/* Generated by tools/v4_games_to_c.py: version 4 stories for the multi-game V4 firmware. */\n")
        f.write("#include <stdint.h>\n#include <stddef.h>\n#include \"v4_games.h\"\n\n")
        for n, g in enumerate(games):
            d = g["data"]
            f.write(f"/* {g['name']}: {len(d)} bytes ({os.path.basename(g['path'])}) */\n")
            f.write(f"static const uint8_t v4_story_{n}[] = {{\n")
            for k in range(0, len(d), 16):
                f.write("    " + ", ".join(f"0x{b:02x}" for b in d[k:k + 16]) + ",\n")
            f.write("};\n\n")
        f.write("const v4_game_t v4_games[] = {\n")
        for n, g in enumerate(games):
            f.write(f"    {{ {c_string(g['name'])}, v4_story_{n}, {len(g['data'])} }},\n")
        f.write("};\n")
        f.write(f"const int v4_num_games = {len(games)};\n")
    print(f"{len(games)} stories, {total} bytes, story buffer {buffer_size(games)}: {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
